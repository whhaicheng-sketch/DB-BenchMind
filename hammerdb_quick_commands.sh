#!/bin/bash
# HammerDB SQL Server 快速命令参考

cat << 'REF'
╔════════════════════════════════════════════════════════════╗
║     HammerDB SQL Server - 快速命令参考卡                    ║
╚════════════════════════════════════════════════════════════╝

════════════════════════════════════════════════════════════
【配置阶段】复制粘贴以下命令到 hammerdb>
════════════════════════════════════════════════════════════

dbset db mssqls
dbset bm TPC-C
diset connection mssqls_linux_server 192.168.134.129
diset connection mssqls_tcp true
diset connection mssqls_uid sa
diset connection mssqls_pass SqlServer@2019
diset tpcc mssqls_count_ware 10
diset tpcc mssqls_num_vu 10
diset tpcc mssqls_dbase tpcc

════════════════════════════════════════════════════════════
【执行 buildschema】
════════════════════════════════════════════════════════════

vudestroy
buildschema
yes

════════════════════════════════════════════════════════════
【验证】在系统命令行执行
════════════════════════════════════════════════════════════

sqlcmd -S 192.168.134.129,1433 -U sa -P 'SqlServer@2019' -C \
  -d tpcc -Q "SELECT COUNT(*) FROM customer"

预期结果: 30000

════════════════════════════════════════════════════════════
【压测阶段】(可选)
════════════════════════════════════════════════════════════

loadscript
vuset vu 10
vucreate
tcset refreshrate 10
tcstart
vurun
# 等待7分钟...
tcstop
vudestroy

════════════════════════════════════════════════════════════
【配置说明】
════════════════════════════════════════════════════════════

• count_ware: 10  = 约1GB数据
• num_vu:     10  = 并发用户数
• rampup:     2   = 预热2分钟
• duration:   5   = 测试5分钟
• allwarehouse: true = 全仓库访问

════════════════════════════════════════════════════════════
【时间估算】
════════════════════════════════════════════════════════════

buildschema:  5-10 分钟
压测运行:      7 分钟 (2+5)
总计:         12-17 分钟

